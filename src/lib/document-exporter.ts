/*  Markdown → docx Paragraph[] builder                                */
/* ------------------------------------------------------------------ */

/** Parse a single line's inline bold/italic markup into TextRun[]. */
function parseInlineRuns(line: string): TextRun[] {
  const runs: TextRun[] = []
  // Split on bold (**…**) and italic (*…*) patterns, keeping delimiters.
  const parts = line.split(/(\*\*.*?\*\*|\*.*?\*)/g)
  for (const part of parts) {
    if (!part) continue
    if (part.startsWith('**') && part.endsWith('**')) {
      runs.push(new TextRun({ text: part.slice(2, -2), bold: true }))
    } else if (part.startsWith('*') && part.endsWith('*')) {
      runs.push(new TextRun({ text: part.slice(1, -1), italic: true }))
    } else {
      runs.push(new TextRun({ text: part }))
    }
  }
  return runs
}

/** Convert a Markdown string into an array of docx Paragraphs. */
function markdownToParagraphs(text: string): Paragraph[] {
  const lines = text.split('\n')
  const children: Paragraph[] = []

  for (const rawLine of lines) {
    const line = rawLine.trimEnd()

    // Empty line → spacer
    if (!line.trim()) {
      children.push(new Paragraph({ text: '' }))
      continue
    }

    // Horizontal rule (---, ___, ***)
    if (/^(-{3,}|_{3,}|\*{3,})$/.test(line.trim())) {
      children.push(
        new Paragraph({
          spacing: { before: 120, after: 120 },
          border: {
            bottom: {
              style: BorderStyle.SINGLE,
              size: 6,
              color: '999999',
              space: 1,
            },
          },
        }),
      )
      continue
    }

    // Heading 1
    if (line.startsWith('# ')) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: line.slice(2).replace(/[*_#]/g, '').toUpperCase(),
              bold: true,
              size: 32, // 16pt
              font: 'Georgia',
            }),
          ],
          heading: HeadingLevel.HEADING_1,
          alignment: AlignmentType.CENTER,
          spacing: { before: 360, after: 240 },
        }),
      )
      continue
    }

    // Heading 2
    if (line.startsWith('## ')) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: line.slice(3).replace(/[*_#]/g, ''),
              bold: true,
              size: 26, // 13pt
              font: 'Georgia',
              underline: { type: UnderlineType.SINGLE },
            }),
          ],
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 240, after: 120 },
        }),
      )
      continue
    }

    // Heading 3
    if (line.startsWith('### ')) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: line.slice(4).replace(/[*_#]/g, ''),
              bold: true,
              size: 24, // 12pt
              font: 'Georgia',
            }),
          ],
          heading: HeadingLevel.HEADING_3,
          spacing: { before: 180, after: 90 },
        }),
      )
      continue
    }

    // Bullet list items (- item or * item)
    if (/^\s*[-*]\s+/.test(line)) {
      const content = line.replace(/^\s*[-*]\s+/, '')
      children.push(
        new Paragraph({
          children: parseInlineRuns(content),
          bullet: { level: 0 },
          spacing: { after: 60, line: 276 },
        }),
      )
      continue
    }

    // Numbered list items (1. item)
    if (/^\s*\d+\.\s+/.test(line)) {
      const content = line.replace(/^\s*\d+\.\s+/, '')
      children.push(
        new Paragraph({
          children: parseInlineRuns(content),
          numbering: { reference: 'iroko-numbering', level: 0 },
          spacing: { after: 60, line: 276 },
        }),
      )
      continue
    }

    // Signature underlines (_____)
    if (/^_{3,}/.test(line.trim())) {
      children.push(
        new Paragraph({
          children: [
            new TextRun({
              text: '___________________________',
              font: 'Georgia',
            }),
          ],
          spacing: { before: 240, after: 60 },
        }),
      )
      continue
    }

    // Normal paragraph
    children.push(
      new Paragraph({
        children: parseInlineRuns(line),
        alignment: AlignmentType.JUSTIFY,
        spacing: { after: 120, line: 276 },
      }),
    )
  }

  return children
}

/* ------------------------------------------------------------------ */
/*  Download as native .docx  (client-side Packer, server fallback)    */
/* ------------------------------------------------------------------ */

/** Download document as TRUE native Microsoft Word (.docx) file. */
export async function downloadAsWord(
  rawText: string,
  title?: string,
): Promise<void> {
  // Strip disclaimer before export — it's visible in chat but not in the file
  const text = stripDisclaimerForExport(rawText)
  const docTitle = title || extractDocTitle(text)
  const filename = docTitle
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')

  try {
    // Client-side generation using docx Packer
    const paragraphs = markdownToParagraphs(text)
    const doc = new Document({
      numbering: {
        config: [
          {
            reference: 'iroko-numbering',
            levels: [
              {
                level: 0,
                format: 'decimal' as any,
                text: '%1.',
                alignment: AlignmentType.START,
              },
            ],
          },
        ],
      },
      sections: [
        {
          properties: {
            page: {
              margin: {
                top: 1440,    // 1 inch in DXA
                right: 1440,
                bottom: 1440,
                left: 1440,
              },
            },
          },
          children: paragraphs,
        },
      ],
    })

    const blob = await Packer.toBlob(doc)
    triggerDownload(blob, `${filename}.docx`)
  } catch (clientErr) {
    console.warn(
      '[downloadAsWord] Client-side Packer failed, falling back to server:',
      clientErr,
    )

    // Server-side fallback
    try {
      const res = await fetch('/api/generate-document/docx', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ text, title: docTitle }),
      })
      if (!res.ok) throw new Error(`Server returned ${res.status}`)
      const blob = await res.blob()
      triggerDownload(blob, `${filename}.docx`)
    } catch (serverErr) {
      console.error('[downloadAsWord] Server fallback also failed:', serverErr)
    }
  }
}


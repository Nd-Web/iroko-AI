/**
 * Client-side Document Exporter for Iroko AI.
 *
 * Uses the official `docx` library (via Packer.toBlob) to generate native
 * Microsoft Word (.docx) files — real Office Open XML, not HTML-in-.doc.
 *
 * Falls back to the server endpoint `/api/generate-document/docx` when
 * client-side Packer is unavailable (e.g. very old browsers, SSR context).
 *
 * PDF uses the browser's native print-to-PDF engine via window.open().
 */

import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  AlignmentType,
  HeadingLevel,
  BorderStyle,
  UnderlineType,
} from 'docx'

/* ------------------------------------------------------------------ */
/*  Detection helpers                                                  */
/* ------------------------------------------------------------------ */

/** Check if text content is a formal legal document, contract, or formal letter. */
export function isLegalDocument(text: string): boolean {
  if (!text || text.length < 150) return false

  // 1. Explicit document heading (# TENANCY AGREEMENT, # DEMAND NOTICE, etc.)
  const hasDocHeading =
    /^#\s+.*(agreement|contract|letter|notice|memorandum|resolution|deed|invoice|affidavit|declaration|demand)/im.test(
      text,
    )
  if (hasDocHeading) return true

  // 2. Formal letter structure (works with real names, not just [placeholders])
  const hasLetterStructure =
    (text.includes('Dear ') ||
      text.includes('RE:') ||
      text.includes('Subject:')) &&
    (text.includes('Yours faithfully') ||
      text.includes('Yours sincerely') ||
      text.includes('Yours truly'))
  if (hasLetterStructure) return true

  // 3. Formal contract / legal agreement structural elements
  const lower = text.toLowerCase()
  const contractKeywords = [
    'in witness whereof',
    'now it is hereby agreed',
    'terms and conditions',
    'whereas the',
    'hereinafter',
    'this agreement is made',
  ]
  const matchCount = contractKeywords.filter((k) => lower.includes(k)).length
  if (matchCount >= 2) return true

  return false
}

/** Extract document title from markdown heading or first line. */
export function extractDocTitle(text: string): string {
  const match = text.match(/^#\s+(.+)$/m)
  if (match?.[1]) {
    return match[1].replace(/[*_#]/g, '').trim()
  }

  const letterSubj = text.match(/(?:Subject|RE):\s*(.+)$/im)
  if (letterSubj?.[1]) {
    return letterSubj[1]
      .replace(/[*_#]/g, '')
      .trim()
      .slice(0, 50)
  }

  const lines = text.split('\n').filter((l) => l.trim().length > 0)
  if (lines[0]) {
    return lines[0]
      .replace(/[*_#]/g, '')
      .trim()
      .slice(0, 50)
  }
  return 'Iroko_Document'
}

/**
 * Strip the Iroko AI disclaimer and trailing HR separator from text
 * before exporting to Word/PDF. The disclaimer is visible in chat
 * but should NOT appear in the downloadable document.
 */
export function stripDisclaimerForExport(text: string): string {
  let cleaned = text

  // Remove the Iroko AI disclaimer paragraph (italic or plain)
  // Matches: *This document was generated by Iroko AI...* or plain text version
  cleaned = cleaned.replace(
    /\n*\*?This document was generated by Iroko AI[\s\S]*?(?:before signing or relying on it\.?)\*?\s*$/i,
    '',
  )

  // Remove trailing horizontal rule separator (---) that precedes the disclaimer
  cleaned = cleaned.replace(/\n---\s*$/, '')

  return cleaned.trimEnd()
}

